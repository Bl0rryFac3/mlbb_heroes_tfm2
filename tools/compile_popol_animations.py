"""Compile supplied native-size sheets; derive alpha-only shields and mirrored variants."""
from pathlib import Path
import json, hashlib
from PIL import Image, ImageOps
ROOT=Path(__file__).resolve().parents[1]
SRC=ROOT/'source/popol_kupa/received'
ADJ=ROOT/'source/popol_kupa/adjusted'; ADJ.mkdir(exist_ok=True)
report={}
for name in ['S2 Shield Start.png','S2 Shield Loop.png']:
    im=Image.open(SRC/name).convert('RGBA'); old=im.copy()
    pixels=[]
    for r,g,b,a in im.getdata():
        # Gray fill 18%; luminous cyan rim/sparks 60%; darker rim 35%.
        factor=.18 if max(r,g,b)-min(r,g,b)<45 else (.60 if b>200 and g-r>35 else .35)
        pixels.append((r,g,b,round(a*factor)))
    im.putdata(pixels); im.save(ADJ/name)
    assert im.size==old.size and im.convert('RGB').tobytes()==old.convert('RGB').tobytes()
    assert all(a[3]==0 for a,b in zip(im.getdata(),old.getdata()) if b[3]==0)
    report[name]={'source_sha256':hashlib.sha256((SRC/name).read_bytes()).hexdigest(),'rgb_unchanged':True,'size':list(im.size),'alpha_only':True}

def compile_sheet(stem,filename,total,ground,seconds):
    im=Image.open((ADJ if filename.startswith('S2 Shield') else SRC)/filename).convert('RGBA')
    cols=3 if total==9 else 1;rows=3 if total==9 else 1
    w,h=im.width//cols,im.height//rows
    assert im.width%cols==0 and im.height%rows==0
    for left in [False,True]:
        # Mirror each cell independently, retaining row-major frame order.
        sheet=im.copy()
        if left:
            for i in range(total):
                x,y=i%cols*w,i//cols*h
                sheet.paste(ImageOps.mirror(im.crop((x,y,x+w,y+h))),(x,y))
        path=ROOT/'effects'/('popol_anim_'+stem+('_left' if left else ''))
        sheet.save(str(path)+'#sheet.png')
        frames=[{'duration':seconds/total,'data':{'x':i%cols*w,'y':i//cols*h,'w':w,'h':h}}for i in range(total)]
        Path(str(path)+'#anim.fanim').write_text(json.dumps({'anchor_x':.5,'anchor_y':ground/h,'anims':{'main':{'frames':frames}}},indent=1)+'\n')
    return w,h

registry=[]
def add(form,motions,cell,ground):
    for motion in motions:
        name=f'{form}_{motion}'; filename=name+'.png'
        seconds={'run':.6,'idle':1.2,'start':.35,'end':.35,'hit':.2,'dead':.9,'attack':.33,'skill':.3,'skill2':.3,'ult':.3,'pray':1.,'transform':.6}.get(motion,.9)
        # Supplied start scenes are wider but retain their original 96px height.
        actual_ground=79 if motion=='start' else ground
        compile_sheet(name,filename,9,actual_ground,seconds)
        registry.append((name,form,motion))
add('popol',['idle','run','attack','skill','skill2','ult','hit','dead','pray'],72,55)
add('kupa',['idle','run','attack','skill','hit','dead'],96,55)
add('kupa_alpha',['idle','run','attack','skill','transform'],112,71)
add('mount',['idle','run','start','end','hit'],112,79)
add('mount_alpha',['idle','run','start','end','hit'],128,95)
for stem,filename,ground,seconds in [('shield_start','S2 Shield Start.png',72,.45),('shield_loop','S2 Shield Loop.png',72,.9),('recall','Kupa Recall Cue.png',55,.6),('prayer','Popol Prayer.png',55,1.),('revival','Kupa Revival Burst.png',79,.6)]:
    compile_sheet(stem,filename,9,ground,seconds)

# Preserve existing idle buff IDs for callback compatibility.
aliases={'popol_idle':'mlbb_popol_probe_body','kupa_idle':'mlbb_kupa_probe_body','kupa_alpha_idle':'mlbb_kupa_probe_alpha','mount_idle':'mlbb_popol_probe_ride'}
bindings=[]
for name,form,motion in registry:
    for left in [False,True]:
        stem=name+('_left' if left else '')
        buff=aliases.get(name,'mlbb_pk_'+name)+('_left' if left else '')
        bindings.append((form,motion,left,buff,stem))
views=[{'type':'Animated','name':buff,'anim':'asset/mlbb_heroes/effects/popol_anim_'+stem,'tag':'main','z':1}for _,_,_,buff,stem in bindings]
for name in ['shield_start','shield_loop','recall','prayer','revival']:
    views.append({'type':'Animated','name':'mlbb_pk_fx_'+name,'anim':'asset/mlbb_heroes/effects/popol_anim_'+name,'tag':'main','z':2})
effects=[]
compile_sheet('spear','basic-attack projectile.png',1,36,.12)
for name in ['popol_dead','kupa_dead','kupa_alpha_transform','revival']:
    for left in [False,True]:
        stem=name+('_left' if left else '')
        effects.append({'type':'Animation','name':'mlbb_pk_once_'+stem,'anim':'asset/mlbb_heroes/effects/popol_anim_'+stem,'tag':'main','z':1,'is_follow':False})
for p in [ROOT/'champion/mlbb_popol_kupa.data_champion',ROOT/'sdk/champion/mlbb_popol_kupa.data_champion',ROOT/'sdk/candidate/champion/mlbb_popol_kupa.data_champion']:
    d=json.loads(p.read_text());d['view_buffs']=views;d['view_effects']=effects
    d['view_projectiles']=[{'type':'Animated','name':'mlbb_pk_spear','anim':'asset/mlbb_heroes/effects/popol_anim_spear','tag':'main','z':1,'repeat':True}]
    p.write_text(json.dumps(d,indent=1)+'\n')
lines=['// Generated by tools/compile_popol_animations.py; frame identities are stable.','pub(super) const BINDINGS: &[(&str, &str, bool, &str)] = &[']
lines += [f'    ("{f}", "{m}", {str(l).lower()}, "{b}"),'for f,m,l,b,_ in bindings]
lines+= ['];']
(ROOT/'sdk/candidate/popol_visual_bindings.rs').write_text('\n'.join(lines)+'\n')
(ROOT/'reports/POPOL_ANIMATION_ALPHA.json').write_text(json.dumps(report,indent=2)+'\n')
print('Compiled 35 sheets with exact cells and per-frame mirrored variants; shield RGB preserved.')
