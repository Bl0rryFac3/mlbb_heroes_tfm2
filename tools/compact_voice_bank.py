#!/usr/bin/env python3
"""Use one existing voice recording per cue in the current build tree."""

from __future__ import annotations

import argparse
from collections import defaultdict
import json
import re
from pathlib import Path
import wave

ROOT = Path(__file__).resolve().parents[1]
SFX = ROOT / "sound/sfx"
CLIP_ROUTES = ROOT / "mod.override_info"
DIRECT_VOICES = ROOT / "sdk/candidate/voice_clips.rs"
DIRECT_PREFIXES = ("mlbb_julian_voice_", "mlbb_popol_voice_", "mlbb_granger_voice_", "mlbb_atlas_voice_")
VARIANTS = re.compile(r"(_voice_(?:move|basic|attack|death|ult|kill|respawn|lord|recall))\d+$")
# These labels track the source audio catalogue rather than the game's skill slots.
SKILL_GROUPS = {
    "mlbb_valir_voice_skill01": "mlbb_valir_s1",
    "mlbb_valir_voice_skill02": "mlbb_valir_s1",
    "mlbb_valir_voice_skill03": "mlbb_valir_s2",
    "mlbb_valir_voice_skill04": "mlbb_valir_s2",
    "mlbb_chou_voice_skill1_a": "mlbb_chou_s1",
    "mlbb_chou_voice_skill1_b": "mlbb_chou_s1",
    "mlbb_aldous_voice_ult_phase2": "mlbb_aldous_voice_ult",
    "mlbb_gusion_voice_ult_recast": "mlbb_gusion_voice_ult",
}
# Keep the first line on staged or two-part ultimates.
LEAD_ULTS = {"mlbb_alpha_ult_cast", "mlbb_karrie_voice_ult", "mlbb_aldous_voice_ult", "mlbb_gusion_voice_ult"}


def is_voice(clip: str) -> bool:
    return any(marker in clip for marker in ("_voice_", "_sfx_vo_", "_hawkwatch_"))


def cue(event: str) -> str:
    return SKILL_GROUPS.get(event, VARIANTS.sub(r"\1", event))


def duration(clip: str) -> float:
    with wave.open(str(SFX / f"{clip}.wav"), "rb") as audio:
        return audio.getnframes() / audio.getframerate()


def compact_events(events):
    groups = defaultdict(list)
    for event, data in events.items():
        for play in data["plays"]:
            if is_voice(play["clip"]):
                groups[cue(event)].append(play["clip"])
    chosen = {
        group: clips[0] if group in LEAD_ULTS else min(set(clips), key=lambda clip: (duration(clip), clip))
        for group, clips in groups.items()
    }
    compact = {}
    for event, data in events.items():
        plays = []
        has_voice = False
        for play in data["plays"]:
            if not is_voice(play["clip"]):
                plays.append(play)
            elif not has_voice:
                plays.append({**play, "clip": chosen[cue(event)]})
                has_voice = True
        compact[event] = {**data, "plays": plays}
    return compact, chosen


def direct_source(events) -> str:
    lines = [
        "// Generated by tools/compact_voice_bank.py from the shipped sound events.",
        "pub(super) fn direct_voice_clip(event: &str) -> &str {",
        "    match event {",
    ]
    grouped = defaultdict(list)
    for event, data in events.items():
        if event.startswith(DIRECT_PREFIXES):
            plays = data["plays"]
            assert len(plays) == 1 and is_voice(plays[0]["clip"]), event
            grouped[plays[0]["clip"]].append(event)
    for clip, aliases in sorted(grouped.items()):
        for index, event in enumerate(aliases):
            prefix = "        " if index == 0 else "        | "
            last = index == len(aliases) - 1
            lines.append(f'{prefix}"{event}"' + (f' => "{clip}",' if last else ""))
    lines.extend(["        _ => event,", "    }", "}", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--apply", action="store_true", help="apply changes to this build tree")
    args = parser.parse_args()
    events = {
        path.stem: json.loads(path.read_text())
        for path in sorted(SFX.glob("*.sound_info"))
    }
    compact, chosen = compact_events(events)
    live_clips = {play["clip"] for data in compact.values() for play in data["plays"]}
    old_waves = {p.stem for p in SFX.glob("*.wav")}
    assert live_clips <= old_waves, f"Missing WAVs: {sorted(live_clips - old_waves)}"
    assert not live_clips & events.keys(), "Sound events and clips must have distinct IDs"
    removed = {clip for clip in old_waves - live_clips if is_voice(clip)}
    routes = json.loads(CLIP_ROUTES.read_text())
    for clip in removed - events.keys():
        alias = f"asset/base/sound/sfx/{clip}"
        if routes.get(alias, {}).get("remapping") == f"asset/mlbb_heroes/sound/sfx/{clip}":
            del routes[alias]
    for name in events.keys() | live_clips:
        alias = f"asset/base/sound/sfx/{name}"
        assert routes.get(alias, {}).get("remapping") == f"asset/mlbb_heroes/sound/sfx/{name}", alias

    changed = {name for name in events if events[name] != compact[name]}
    print(f"{len(chosen)} voice cues, {len(set(chosen.values()))} WAVs, {len(changed)} updated events")
    print(f"{len(removed)} redundant voice WAVs, {sum((SFX / f'{clip}.wav').stat().st_size for clip in removed):,} bytes")
    output = direct_source(compact)
    if not args.apply:
        return
    for event in sorted(changed):
        (SFX / f"{event}.sound_info").write_text(json.dumps(compact[event], indent=2) + "\n")
    CLIP_ROUTES.write_text(json.dumps(routes, indent=2, ensure_ascii=False) + "\n")
    DIRECT_VOICES.write_text(output)
    for clip in sorted(removed):
        (SFX / f"{clip}.wav").unlink()


if __name__ == "__main__":
    main()
